import { spawn, execFileSync } from 'node:child_process';
import { mkdir, readFile, readdir, realpath, symlink, writeFile, rm, cp, lstat } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import net from 'node:net';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Failure boundaries: never use production data, inherit credentials, alter the
// checkout, or hide a CORS failure while comparing two production Web builds.
// Reject expired sessions and occupied ports before building; never report an
// unrelated server as ready, and retire metadata when the owned server stops.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const [sessionFile, portText = '61081', baselineRef = 'HEAD', ...extra] = process.argv.slice(2);
const snapshotArgument = extra[0]?.startsWith('--snapshot=') ? extra[0].slice('--snapshot='.length) : null;
if (extra.length > 1 || (extra.length && !snapshotArgument) || (baselineRef !== 'HEAD' && !/^[a-f0-9]{40}$/.test(baselineRef))) {
  throw new Error('Baseline source must be HEAD or an explicit full Git commit SHA.');
}
if (!sessionFile) throw new Error('Usage: node scripts/performance/serve-baseline.mjs <isolated-session.json> [port] [commit-sha] [--snapshot=<manifest>]');
const session = JSON.parse(await readFile(sessionFile, 'utf8'));
if (!/^[a-f0-9]{12}$/.test(session.runId ?? '') ||
    await realpath(sessionFile) !== path.join(root, 'artifacts/e2e', session.runId, 'session.json')) {
  throw new Error('Use the session.json generated by the isolated E2E runner.');
}
const expiresAt = Date.parse(session.expiresAt);
function checkExpiry() {
  if (!Number.isFinite(expiresAt) || expiresAt <= Date.now() || expiresAt - Date.now() > 90 * 60_000) {
    throw new Error('The isolated session must have a valid future expiry within 90 minutes.');
  }
}
checkExpiry();
const port = Number(portText);
if (!Number.isInteger(port) || port < 1024 || port > 65535) throw new Error('Invalid local port.');
for (const raw of [session.apiUrl, session.webUrl]) {
  const url = new URL(raw);
  if (url.protocol !== 'http:' || url.hostname !== '127.0.0.1' || !url.port) throw new Error('Only disposable loopback sessions are allowed.');
}
const beforeUrl = `http://127.0.0.1:${port}`;
async function checkPort() {
  const probe = net.createServer();
  await new Promise((resolve, reject) => {
    probe.once('error', reject);
    probe.listen(port, '127.0.0.1', resolve);
  });
  await new Promise((resolve, reject) => probe.close(error => error ? reject(error) : resolve()));
}
await checkPort();
const cors = await fetch(`${session.apiUrl}/public/schools`, { headers: { Origin: beforeUrl }, signal: AbortSignal.timeout(5000) });
if (!cors.ok || cors.headers.get('access-control-allow-origin') !== beforeUrl) {
  throw new Error(`Start the runner with --extra-client-origin=${beforeUrl}; CORS must be real, not bypassed.`);
}
const revision = execFileSync('git', ['rev-parse', '--verify', `${baselineRef}^{commit}`], { cwd: root, encoding: 'utf8' }).trim();
// A dirty-tree comparison needs its own frozen source, not a later Git HEAD.
// Verify every listed source and reject credentials, traversal and symlinks.
let snapshot;
if (snapshotArgument) {
  const manifestPath = await realpath(snapshotArgument);
  if (!manifestPath.startsWith(`${path.join(root, 'artifacts')}${path.sep}`)) throw new Error('Snapshot manifest must belong to local artifacts.');
  snapshot = JSON.parse(await readFile(manifestPath, 'utf8'));
  if (!Array.isArray(snapshot.files) || !snapshot.files.length || !/^[a-f0-9]{64}$/.test(snapshot.sourceDigest ?? '')) throw new Error('Invalid source snapshot.');
  if (createHash('sha256').update(JSON.stringify(snapshot.files)).digest('hex') !== snapshot.sourceDigest) throw new Error('Snapshot manifest digest mismatch.');
  snapshot.directory = path.join(path.dirname(manifestPath), 'before-source');
  for (const file of snapshot.files) {
    if (!/^(?:apps\/web\/|packages\/shared\/|scripts\/images\/|package(?:-lock)?\.json$)/.test(file.path)
      || file.path.split('/').some(part => part === '..' || part.startsWith('.env')) || !/^[a-f0-9]{64}$/.test(file.sha256)) throw new Error('Invalid snapshot source path.');
    const source = path.join(snapshot.directory, file.path);
    if (!(await lstat(source)).isFile() || await realpath(source) !== source) throw new Error('Snapshot source must be a regular file.');
    if (createHash('sha256').update(await readFile(source)).digest('hex') !== file.sha256) throw new Error(`Snapshot source changed: ${file.path}`);
  }
}
const output = path.join(root, 'artifacts/performance', `baseline-${session.runId}`);
const workspace = path.join(output, 'workspace');
await mkdir(output, { recursive: true });
await mkdir(workspace);
const children = new Set();
let stopped = false;
let forceStop;
let stop;
const stopSignal = new Promise(resolve => { stop = resolve; });
const env = Object.fromEntries(['PATH', 'HOME', 'TMPDIR', 'TEMP', 'SystemRoot'].filter(key => process.env[key]).map(key => [key, process.env[key]]));
Object.assign(env, { NODE_ENV: 'production', NEXT_PUBLIC_API_BASE_URL: session.apiUrl,
  NEXT_PUBLIC_SENTRY_DSN: '', SENTRY_DSN: '', NEXT_TELEMETRY_DISABLED: '1',
  LILINK_BUILD_WORKSPACE_ROOT: root });
function command(exe, args) {
  if (stopped) throw new Error('The isolated session has stopped.');
  const child = spawn(exe, args, { cwd: workspace, env, stdio: 'inherit', detached: true });
  children.add(child);
  child.done = new Promise((resolve, reject) => {
    child.on('error', reject);
    child.on('exit', code => { children.delete(child); code === 0 ? resolve() : reject(new Error(`${exe} exited ${code}`)); });
  });
  child.done.catch(() => {});
  return child;
}
function requestStop() {
  if (stopped) return;
  stopped = true; stop();
  for (const child of children) { try { process.kill(-child.pid, 'SIGTERM'); } catch {} }
  forceStop = setTimeout(() => {
    for (const child of children) { try { process.kill(-child.pid, 'SIGKILL'); } catch {} }
  }, 3000);
  forceStop.unref();
}
for (const signal of ['SIGTERM', 'SIGINT']) process.once(signal, requestStop);
async function links(source, target, isRoot = false) {
  let entries;
  try { entries = await readdir(source); } catch (error) { if (error.code === 'ENOENT') return; throw error; }
  await mkdir(target, { recursive: true });
  for (const entry of entries) {
    if (isRoot && ['@lilink', 'api', 'web'].includes(entry)) continue;
    await symlink(path.join(source, entry), path.join(target, entry));
  }
  if (isRoot) {
    await mkdir(path.join(target, '@lilink'));
    await symlink(path.join(workspace, 'packages/shared'), path.join(target, '@lilink/shared'));
    await symlink(path.join(workspace, 'apps/web'), path.join(target, 'web'));
  }
}
let record;
const expiry = setTimeout(requestStop, expiresAt - Date.now());
try {
  if (snapshot) {
    for (const file of snapshot.files) {
      const target = path.join(workspace, file.path);
      await mkdir(path.dirname(target), { recursive: true });
      await cp(path.join(snapshot.directory, file.path), target);
    }
  } else {
    const sources = ['apps/web', 'packages/shared', 'package.json', 'package-lock.json'];
    if (execFileSync('git', ['ls-tree', '--name-only', revision, 'scripts/images'], { cwd: root, encoding: 'utf8' }).trim()) sources.push('scripts/images');
    const archive = execFileSync('git', ['archive', revision, ...sources], { cwd: root, maxBuffer: 128 * 1024 * 1024 });
    execFileSync('tar', ['-xf', '-', '-C', workspace], { input: archive });
  }
  await links(path.join(root, 'node_modules'), path.join(workspace, 'node_modules'), true);
  await links(path.join(root, 'apps/web/node_modules'), path.join(workspace, 'apps/web/node_modules'));
  await command('npm', ['run', 'build:shared']).done;
  await command('npm', ['run', 'build:web']).done;
  if (stopped) throw new Error('Interrupted.');
  checkExpiry();
  await checkPort();
  const server = command('npm', ['run', 'start', '--workspace', 'web', '--', '--hostname', '127.0.0.1', '--port', String(port)]);
  const deadline = Date.now() + 60_000;
  let ready = false;
  while (Date.now() < deadline && !stopped) {
    if (server.exitCode !== null || server.signalCode !== null) throw new Error('Baseline server exited before readiness.');
    try { ready = (await fetch(beforeUrl, { signal: AbortSignal.timeout(2000) })).ok; } catch {}
    if (server.exitCode !== null || server.signalCode !== null) throw new Error('Baseline server exited during readiness.');
    if (ready) break;
    await Promise.race([new Promise(resolve => setTimeout(resolve, 300)), server.done]);
  }
  if (!ready || stopped) throw new Error('Baseline did not become ready.');
  checkExpiry();
  record = { active: true, revision: snapshot ? null : revision, sourceDigest: snapshot?.sourceDigest,
    sourceSnapshot: snapshotArgument ? path.resolve(snapshotArgument) : undefined,
    baseline: snapshot ? 'frozen uncommitted working tree before resource optimization' : baselineRef === 'HEAD' ? 'git HEAD' : 'explicit Git commit; verify against production deployment metadata', beforeUrl,
    afterUrl: session.webUrl, apiUrl: session.apiUrl, cdnUrl: session.cdnUrl,
    sourceSession: path.resolve(sessionFile), sharedSyntheticData: true, pid: process.pid,
    productionDeployment: false, expiresAt: session.expiresAt };
  await writeFile(path.join(output, 'comparison-session.json'), JSON.stringify(record, null, 2));
  console.log(JSON.stringify({ ready: true, output, ...record }));
  await Promise.race([server.done.then(() => { throw new Error('Baseline server exited unexpectedly.'); }), stopSignal]);
} finally {
  clearTimeout(expiry);
  const live = [...children];
  for (const child of live) { try { process.kill(-child.pid, 'SIGTERM'); } catch {} }
  await Promise.race([Promise.allSettled(live.map(child => child.done)), new Promise(resolve => setTimeout(resolve, 3000))]);
  for (const child of live) { try { process.kill(-child.pid, 'SIGKILL'); } catch {} }
  clearTimeout(forceStop);
  await rm(workspace, { recursive: true, force: true });
  if (record) await writeFile(path.join(output, 'comparison-session.json'), JSON.stringify({
    ...record, active: false, stoppedAt: new Date().toISOString(),
  }, null, 2));
}
