import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const publicRoot = path.join(root, 'apps/web/public');
const outputRoot = path.join(publicRoot, 'images/responsive');
const manifestPath = path.join(root, 'apps/web/src/lib/static-image-manifest.ts');
const hash = bytes => createHash('sha256').update(bytes).digest('hex');

// Published source files are explicit and never replaced by generated variants.
const homeSource = 'images/campus-blossom-scene-anime.5ee78102b043.webp';
const sources = [
  [homeSource, [384, 640, 750, 828, 1080]],
  ['images/campus-evening-anime.2b6f7201560b.webp', [384, 640, 750, 828, 1080, 1200]],
  ['images/campus-clean-romance.fdd0f4cc2596.webp', [384, 640, 750, 1080]],
  ['images/campus-couple-anime.74b2881afd58.webp', [384, 640, 750, 1080]],
  ['images/one-to-one-minimal.6c30b4067e80.webp', [384, 640, 750, 828, 1080, 1200]],
  ['images/about/yoryon.f1f0a575ff59.webp', [112, 224]],
  ['images/about/member-02.b6fbc6031cdb.webp', [112, 224]],
  ['images/about/devillord6321.016e14db36ed.webp', [112, 224]],
  ['images/match-letter-handwritten.8440550c4fe2.webp', [384, 640, 750, 828, 1080]],
];

await mkdir(outputRoot, { recursive: true });
const assets = {};
let outputCount = 0;
let outputBytes = 0;
for (const [sourcePath, widths] of sources) {
  const source = await readFile(path.join(publicRoot, sourcePath));
  const digest = hash(source);
  if (!sourcePath.includes(`.${digest.slice(0, 12)}.webp`)) {
    throw new Error(`Source content hash does not match its URL: ${sourcePath}`);
  }
  const metadata = await sharp(source).metadata();
  if (!metadata.width || !metadata.height || (metadata.pages ?? 1) !== 1) {
    throw new Error(`Source must be a single, dimensioned image: ${sourcePath}`);
  }
  if (sourcePath === homeSource) {
    // The preview shares the full artwork's aspect ratio and CSS crop.
    const preview = await sharp(source).resize({ width: 96, withoutEnlargement: true })
      .webp({ quality: 45, effort: 6 }).toBuffer();
    const css = `/* Generated by scripts/images/generate-responsive.mjs. */\n`
      + `.preview { background-image: url("data:image/webp;base64,${preview.toString('base64')}"); }\n`;
    await writeFile(path.join(root, 'apps/web/src/app/home-preview.generated.module.css'), css);
    console.log(JSON.stringify({ homePreviewBytes: preview.length, cssBytes: Buffer.byteLength(css) }));
  }
  const variantWidths = [...new Set([...widths.filter(width => width < metadata.width), metadata.width])];
  const variants = [];
  const base = path.basename(sourcePath).replace(/\.[a-f0-9]{12}\.webp$/, '');
  for (const width of variantWidths) {
    // The full-resolution variant is byte-identical to the current published art.
    const bytes = width === metadata.width ? source : await sharp(source)
      .resize({ width, withoutEnlargement: true })
      .webp({ quality: 80, alphaQuality: 100, effort: 6, smartSubsample: true })
      .toBuffer();
    const name = `${base}-${width}.${hash(bytes).slice(0, 12)}.webp`;
    const info = await sharp(bytes).metadata();
    if (info.width !== width || !info.height) throw new Error(`Invalid output dimensions: ${name}`);
    await writeFile(path.join(outputRoot, name), bytes);
    variants.push({ src: `/images/responsive/${name}`, width, height: info.height });
    outputCount += 1;
    outputBytes += bytes.length;
  }
  assets[`/${sourcePath}`] = { width: metadata.width, height: metadata.height, variants };
}

const aboutSource = 'images/about/watercolor-atlas.618382ffbabd.webp';
const aboutBytes = await readFile(path.join(publicRoot, aboutSource));
const aboutMetadata = await sharp(aboutBytes).metadata();
if (!aboutSource.includes(`.${hash(aboutBytes).slice(0, 12)}.webp`)
  || aboutMetadata.width !== 2172 || aboutMetadata.height !== 724 || (aboutMetadata.pages ?? 1) !== 1) {
  throw new Error(`About artwork must retain its published hash and three-panel crop: ${aboutSource}`);
}
const aboutPreview = await sharp(aboutBytes).resize({ width: 288, withoutEnlargement: true })
  .webp({ quality: 45, effort: 6 }).toBuffer();
const aboutPreviewCss = `/* Generated by scripts/images/generate-responsive.mjs. */\n`
  + `.preview { background-image: url("data:image/webp;base64,${aboutPreview.toString('base64')}"); }\n`;
await writeFile(path.join(root, 'apps/web/src/app/about/about-preview.generated.module.css'), aboutPreviewCss);
console.log(JSON.stringify({ aboutPreviewBytes: aboutPreview.length, cssBytes: Buffer.byteLength(aboutPreviewCss) }));

const content = `// Generated by scripts/images/generate-responsive.mjs. Do not edit.\n`
  + `export const staticImageManifest = ${JSON.stringify(assets, null, 2)} as const;\n`
  + `\nexport type StaticImageSource = keyof typeof staticImageManifest;\n`;
await writeFile(manifestPath, content);
console.log(JSON.stringify({ sourceCount: sources.length, outputCount, outputBytes, manifest: path.relative(root, manifestPath) }));
