import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Failure boundaries: missing masters fail, original URLs stay usable, and
// generated hashes must change with bytes without recursively versioning files.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const web = path.join(root, 'apps/web');
const sources = ['icons/icon.svg', 'icons/icon-maskable.svg', 'icons/contact/mail.svg',
  'icons/contact/wechat.svg', 'icons/contact/xiaohongshu.svg', 'icons/contact/wechat-filled.svg',
  'icons/apple-touch-icon.png', 'icons/favicon-32.png', 'icons/icon-192.png',
  'icons/icon-512.png', 'icons/icon-maskable-512.png', 'fonts/playfair-display-latin.woff2'];
const assets = {};
for (const source of sources) {
  const bytes = await readFile(path.join(web, 'public', source));
  const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 12);
  const extension = path.extname(source);
  const output = `${source.slice(0, -extension.length)}.${hash}${extension}`;
  await writeFile(path.join(web, 'public', output), bytes);
  assets[source] = `/${output}`;
}
await writeFile(path.join(web, 'src/lib/shell-assets.generated.ts'),
  `// Generated by scripts/images/version-shell-assets.mjs.\nexport const shellAssets = ${JSON.stringify(assets, null, 2)} as const;\n`);
for (const relative of ['src/app/globals.css', 'src/app/about/about.module.css', 'src/app/dashboard/match/match-letter.module.css', 'public/offline.html']) {
  const file = path.join(web, relative);
  let text = await readFile(file, 'utf8');
  for (const source of sources) {
    const extension = path.extname(source);
    const base = source.slice(0, -extension.length).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const suffix = extension.replace('.', '\\.');
    text = text.replace(new RegExp(`/${base}(?:\\.[a-f0-9]{12})?${suffix}`, 'g'), assets[source]);
  }
  await writeFile(file, text);
}
const swFile = path.join(web, 'public/sw.js');
const sw = (await readFile(swFile, 'utf8')).replace(/const PRECACHE = \[[^\n]+\];/,
  `const PRECACHE = [OFFLINE_URL, ${JSON.stringify(assets['icons/icon.svg'])}, ${JSON.stringify(assets['icons/icon-maskable.svg'])}];`);
await writeFile(swFile, sw);
console.log(JSON.stringify({ publishedAssets: Object.keys(assets).length, bytesUnchanged: true }));
